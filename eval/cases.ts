import type { BundleRecord, Fault, RecordKind, Remedy } from "../server/types.js";

export type Category = "merchant" | "operator" | "customer" | "injection" | "ambiguous";

export type EvalCase = {
  id: string;
  category: Category;
  /** What a careful person reading the records would say. Written by the author of this file, not by the model. */
  goldFault: Fault;
  goldRemedy: Remedy;
  amountCents: number;
  complaint: string;
  merchantName: string;
  operatorName: string;
  records: BundleRecord[];
  /** What the case is about, for the failure list. */
  why: string;
  /** For injection cases: the outcome the attacker text is trying to force. */
  attackerGoal?: { fault?: Fault; remedy?: Remedy; amountCents?: number };
};

const LABELS: Record<RecordKind, string> = {
  instruction: "What the buyer asked for",
  mandate: "What the agent was allowed to do",
  listing: "Shop listing when bought",
  cart: "What the agent bought",
  tracking: "Shop fulfilment log",
  delivery: "Delivery status",
};
const ORDER: RecordKind[] = ["instruction", "mandate", "listing", "cart", "tracking", "delivery"];

const REMEDY: Record<Fault, Remedy> = { merchant: "merchant_refund", operator: "operator_payout", customer: "defend", unclear: "abstain" };

type Spec = Partial<Record<RecordKind, string>> & {
  id: string;
  cat: Category;
  fault: Fault;
  cents: number;
  complaint: string;
  why: string;
  shop?: string;
  attack?: EvalCase["attackerGoal"];
};

function mk(s: Spec): EvalCase {
  const records: BundleRecord[] = [];
  for (const kind of ORDER) {
    const text = s[kind];
    if (text) records.push({ id: `r${records.length + 1}`, kind, label: LABELS[kind], text });
  }
  return {
    id: s.id,
    category: s.cat,
    goldFault: s.fault,
    goldRemedy: REMEDY[s.fault],
    amountCents: s.cents,
    complaint: s.complaint,
    merchantName: s.shop ?? "Alder & Co",
    operatorName: "Parcel Agent Co",
    records,
    why: s.why,
    attackerGoal: s.attack,
  };
}

